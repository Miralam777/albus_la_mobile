class CallLocaleModel {
  final String acceptText;
  final String declineText;
  final String missedCallSubtitle;
  final String missedCallCallbackText;
  final String callingSubtitle;
  final String callingCallbackText;

  CallLocaleModel({
    required this.acceptText,
    required this.declineText,
    required this.missedCallSubtitle,
    required this.missedCallCallbackText,
    required this.callingSubtitle,
    required this.callingCallbackText,
  });
}
